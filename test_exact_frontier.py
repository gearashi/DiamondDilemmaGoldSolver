    names = ('exact_frontier.py', 'test_exact_frontier.py')
    def hashes():
        return {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in names}
    before = hashes()
    started_at = datetime.datetime.now(datetime.timezone.utc).isoformat()
    started = time.monotonic()
    suite = unittest.defaultTestLoader.loadTestsFromModule(sys.modules[__name__])
    result = unittest.TextTestRunner(verbosity=2).run(suite)
    after = hashes()
    report = {
        'passed': result.wasSuccessful(), 'tests_run': result.testsRun,
        'failures': len(result.failures), 'errors': len(result.errors),
        'started_at': started_at, 'runtime_seconds': time.monotonic() - started,
        'command': list(sys.orig_argv), 'working_directory': str(ROOT),
        'exit_status': 0 if result.wasSuccessful() else 1,
        'python': sys.version, 'platform': platform.platform(),
        'scope': 'Small exact enumeration (at most 4 tiles and 3 rotations); no puzzle solution or exhaustive 160-tile completion claim',
        'source_sha256_before': before, 'source_sha256_after': after,
        'execution_sources_unchanged': before == after,
    }
    (ROOT / 'exact-frontier-tests.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    raise SystemExit(report['exit_status'])
